import { chromium } from '@playwright/test'
import { createServer } from 'vite'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

await mkdir('test-results',{recursive:true})
const server=await createServer({server:{host:'127.0.0.1',port:0}})
await server.listen()
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-swiftshader']})
try {
  const page=await browser.newPage({viewport:{width:1536,height:811}})
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>{if(message.type()==='error'&&!message.text().includes('net::ERR'))errors.push(message.text())})
  const apiTile=(code,name,family,image,surface='Floor',sort_order=0)=>({code,name,family,finish:family==='Marble'?'Polished':'Matt',surface,image_url:'/tiles/'+image+'.jpg',color:'#d8d4cb',vein:'#7e786f',size:'600 x 1200 mm',normal_url:null,roughness_url:null,texture_repeat:2.6,sort_order,built_in:true,created_at:'2026-09-23T00:00:00Z'})
  const catalog=[apiTile('AT-2048','Ivory Dune','Stone','interior_tiles'),apiTile('AT-2049','Calacatta Gold','Marble','marble_01'),apiTile('AT-2050','Statuario White','Marble','floor_tiles_02'),apiTile('AT-2051','Sage Terrazzo','Terrazzo','old_mosaic_floor'),apiTile('AT-2052','Travertine Sand','Stone','floor_tiles_04'),apiTile('AT-2053','Honey Oak','Wood','wood_floor'),apiTile('AT-2057','Verde Alpi','Marble','stone_tiles_02'),apiTile('MJP-W-1001','Interior Ceramic Wall','Stone','interior_tiles','Wall',100),apiTile('MJP-W-1007','Natural Stone Wall','Stone','stone_tiles','Wall',106)]
  for(let i=0;i<24;i++)catalog.push(apiTile('TEST-'+i,'Catalog test '+i,'Stone','stone_floor','Floor',20+i))
  await page.route('**/api/tile-designs',route=>route.fulfill({json:catalog}))
  await page.goto(server.resolvedUrls.local[0],{waitUntil:'networkidle',timeout:90000})
  await page.getByRole('button',{name:'STEP INSIDE',exact:true}).waitFor({timeout:60000})
  assert.equal(await page.locator('.graphics-error').count(),0)
  const contact=page.locator('#contact')
  await contact.scrollIntoViewIfNeeded()
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Desktop contact design does not overflow the page horizontally')
  await contact.screenshot({path:'test-results/contact-professional-desktop.jpg',type:'jpeg',quality:80})
  await page.setViewportSize({width:390,height:844})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile contact design does not overflow the page horizontally')
  await contact.screenshot({path:'test-results/contact-professional-mobile.jpg',type:'jpeg',quality:80})
  await page.setViewportSize({width:1536,height:811})
  await page.locator('#showroom').scrollIntoViewIfNeeded()
  assert.equal(await page.locator('.room-nav button').count(),8)
  const enterBox=await page.getByRole('button',{name:'STEP INSIDE',exact:true}).boundingBox()
  const navBox=await page.locator('.room-nav').boundingBox()
  assert.ok(enterBox&&navBox&&enterBox.y+enterBox.height<navBox.y,'Hero action and room navigation do not overlap')
  const rooms=[['Cozy living room','cozy-living'],['Modern bedroom','modern-bedroom'],['Simple living room','simple-living'],['Gallery hall','gallery-hall'],['Bathroom','bathroom'],['Office space','office'],['VR gallery','vr-gallery'],['Cooking club','cooking-club']]
  const initialShots=new Map()
  for(const [name,file] of rooms){
    await page.locator('.room-nav').getByRole('button',{name:new RegExp(name)}).click()
    await page.waitForTimeout(2500)
    assert.match(await page.locator('.scene-status').innerText(),new RegExp(name))
    initialShots.set(name,await page.locator('.three-host').screenshot({path:'test-results/imported-'+file+'.jpg',type:'jpeg',quality:72}))
  }
  await page.locator('.room-nav').getByRole('button',{name:/Simple living room/}).click()
  await page.waitForTimeout(800)
  const viewerBox=await page.locator('.three-host').boundingBox()
  assert.ok(viewerBox)
  await page.mouse.click(viewerBox.x+viewerBox.width*.72,viewerBox.y+viewerBox.height*.42)
  await page.locator('.wall-quickbar').waitFor({timeout:5000})
  const proceduralBefore=await page.locator('.three-host').screenshot()
  await page.locator('.wall-quickbar').getByRole('button',{name:'Subway tile',exact:true}).click()
  await page.waitForTimeout(450)
  const proceduralAfter=await page.locator('.three-host').screenshot({path:'test-results/imported-wall-pattern.jpg',type:'jpeg',quality:76})
  assert.ok(!proceduralBefore.equals(proceduralAfter),'Procedural wall design is rendered in the imported 3D room')
  await page.getByRole('button',{name:'Close wall colours',exact:true}).click()
  const floorBefore=await page.locator('.three-host').screenshot()
  await page.getByRole('button',{name:'COLLECTIONS',exact:true}).click()
  const grid=page.getByRole('dialog').locator('.catalog-grid')
  const scrollMetrics=await grid.evaluate(element=>({clientHeight:element.clientHeight,scrollHeight:element.scrollHeight}))
  assert.ok(scrollMetrics.scrollHeight>scrollMetrics.clientHeight,'Collection tile grid has its own scrollable viewport')
  await grid.evaluate(element=>{element.scrollTop=element.scrollHeight})
  assert.ok(await grid.evaluate(element=>element.scrollTop)>0,'Collection tile grid scroll position changes')
  await page.getByRole('combobox',{name:'Collection application scope'}).selectOption('all')
  await page.getByRole('dialog').getByRole('button',{name:'Apply Verde Alpi',exact:true}).click()
  await page.waitForTimeout(1200)
  assert.equal(await page.locator('.product-heading h3').innerText(),'Verde Alpi')
  const floorAfter=await page.locator('.three-host').screenshot()
  assert.ok(!floorBefore.equals(floorAfter),'Applying a collection tile updates the imported 3D floor')
  for(const [name,file] of rooms){
    await page.locator('.room-nav').getByRole('button',{name:new RegExp(name)}).click()
    await page.waitForTimeout(350)
    const changed=await page.locator('.three-host').screenshot({path:'test-results/floor-'+file+'.jpg',type:'jpeg',quality:76})
    assert.ok(!initialShots.get(name).equals(changed),'Floor tile is visible in '+name)
  }
  await page.locator('.room-nav').getByRole('button',{name:/Simple living room/}).click()
  await page.waitForTimeout(350)
  const wallBefore=await page.locator('.three-host').screenshot()
  await page.getByRole('button',{name:'WALL TILES',exact:true}).click()
  await page.getByRole('combobox',{name:'Wall tile target'}).selectOption('10')
  await page.getByRole('dialog').getByRole('button',{name:'Apply Interior Ceramic Wall',exact:true}).click()
  await page.waitForTimeout(1200)
  const wallAfter=await page.locator('.three-host').screenshot({path:'test-results/imported-wall-tile.jpg',type:'jpeg',quality:76})
  assert.ok(!wallBefore.equals(wallAfter),'Applying a wall collection updates the targeted imported wall')
  await page.getByRole('button',{name:'WALL TILES',exact:true}).click()
  await page.getByRole('combobox',{name:'Wall tile target'}).selectOption('14')
  await page.getByRole('dialog').getByRole('button',{name:'Apply Natural Stone Wall',exact:true}).click()
  await page.locator('.room-nav').getByRole('button',{name:/Gallery hall/}).click()
  await page.waitForTimeout(700)
  const galleryWall=await page.locator('.three-host').screenshot({path:'test-results/gallery-clean-wall-tile.jpg',type:'jpeg',quality:80})
  assert.ok(!initialShots.get('Gallery hall').equals(galleryWall),'Gallery Hall wall tile renders as a clean opaque surface')
  assert.deepEqual(errors,[])
  console.log('PASS: all eight imported spaces loaded, navigated and rendered without browser errors')
} finally {await browser.close();await server.close()}
